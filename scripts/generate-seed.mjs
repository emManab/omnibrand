// Generates supabase/seed.sql from the legacy hardcoded catalog (src/data/*).
// Run once:  node scripts/generate-seed.mjs
// The generated SQL is idempotent (ON CONFLICT DO NOTHING) and only needs to be run once on a
// fresh database so the existing Calcuttapress products / categories / banners appear.
import { build } from "esbuild";
import { mkdtempSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const root = resolve(import.meta.dirname, "..");
const tmp = mkdtempSync(join(tmpdir(), "cp-seed-"));
const bundle = join(tmp, "legacy.mjs");

await build({
  stdin: {
    contents: `
      export { products } from "@/data/catalog";
      export { categoryImages } from "@/data/storefrontImages";
      export { heroOffers, promoMedia } from "@/data/mediaAssets";
    `,
    resolveDir: root,
    sourcefile: "entry.ts",
    loader: "ts",
  },
  bundle: true,
  format: "esm",
  platform: "node",
  outfile: bundle,
  alias: { "@": join(root, "src") },
  logLevel: "silent",
});

const { products, categoryImages, heroOffers, promoMedia } = await import(pathToFileURL(bundle).href);
rmSync(tmp, { recursive: true, force: true });

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;
const b = (v) => (v ? "true" : "false");

