// Secondary category for products inside the 8 top-level groups (name heuristics).
function childSlugs(p) {
  const n = `${p.name} ${p.tagline}`.toLowerCase();
  const out = [];
  if (p.category === "apparel") {
    if (/polo/.test(n)) out.push("polo-t-shirts");
    if (/dress shirt|oxford|formal shirt/.test(n)) out.push("dress-shirts");
    if (/t-shirt|tee\b|tees\b/.test(n)) out.push("t-shirts");
    if (/hoodie|sweatshirt|jacket|fleece|beanie|winter/.test(n)) out.push("winter-wear");
  }
  if (p.category === "stationery" && /stamp|ink/.test(n)) out.push("stamps-ink");
  if (p.category === "marketing" && /poster|sign|banner/.test(n)) out.push("signs-posters");
  return out;
}

const L = [];
L.push("-- GENERATED by scripts/generate-seed.mjs from the legacy hardcoded catalog. Idempotent.");
L.push("-- Run once, AFTER all migrations. Products are seeded as published, made-to-order (custom");
L.push("-- printed goods) with inventory tracking off; change this per product in /admin.");
L.push("begin;");
L.push("");
L.push("-- categories (parents first)");
for (const c of cats.filter((c) => !c.parent)) {
  L.push(
    `insert into public.categories (slug, name, nav_label, short_description, image_path, sort_order, is_published, is_featured, show_in_nav) values (${q(c.slug)}, ${q(c.name)}, ${q(c.nav ?? null)}, ${q(c.short)}, ${q(c.img)}, ${c.sort}, true, ${b(c.featured)}, ${b(c.inNav)}) on conflict (slug) do nothing;`,
  );
}
for (const c of cats.filter((c) => c.parent)) {
  L.push(
    `insert into public.categories (slug, parent_id, name, short_description, image_path, sort_order, is_published, is_featured, show_in_nav) values (${q(c.slug)}, (select id from public.categories where slug = ${q(c.parent)}), ${q(c.name)}, ${q(c.short)}, ${q(c.img)}, ${c.sort}, true, ${b(c.featured)}, false) on conflict (slug) do nothing;`,
  );
}

L.push("");
L.push("-- products");
for (const p of products) {
  const sku = `CP-${p.id.toUpperCase()}`;
  const printOptions = { sizes: p.sizes, materials: p.materials, finishes: p.finishes, quantities: p.quantities };
  L.push(
    `insert into public.products (slug, sku, name, tagline, description, price, status, is_featured, is_bestseller, is_trending, is_new, track_inventory, made_to_order, stock_quantity, editor_preset, accent, rating, review_count, print_options) values (${q(p.slug)}, ${q(sku)}, ${q(p.name)}, ${q(p.tagline)}, ${q(p.description)}, ${p.fromPrice}, 'published', ${b(p.featured)}, false, ${b(p.trending)}, ${b(p.newArrival)}, false, true, 0, ${q(p.editorPreset)}, ${q(p.accent)}, ${p.rating}, ${p.reviews}, ${j(printOptions)}) on conflict (slug) do nothing;`,
  );
  L.push(
    `insert into public.product_images (product_id, path, alt, sort_order, is_primary) select id, ${q(p.image)}, ${q(p.name)}, 0, true from public.products where slug = ${q(p.slug)} and not exists (select 1 from public.product_images i where i.product_id = products.id);`,
  );
  L.push(
    `insert into public.product_categories (product_id, category_id, is_primary) select p.id, c.id, true from public.products p, public.categories c where p.slug = ${q(p.slug)} and c.slug = ${q(p.category)} on conflict (product_id, category_id) do nothing;`,
  );
  for (const child of childSlugs(p)) {
    L.push(
      `insert into public.product_categories (product_id, category_id, is_primary) select p.id, c.id, false from public.products p, public.categories c where p.slug = ${q(p.slug)} and c.slug = ${q(child)} on conflict (product_id, category_id) do nothing;`,
    );
  }
}

